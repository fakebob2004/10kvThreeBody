function R=validate_bess_resource_v2()
%VALIDATE_BESS_RESOURCE_V2 Structural and dynamic acceptance for BESS-GFM v2.
root=fileparts(fileparts(mfilename('fullpath')));setup_v2_paths;
define_resource_buses(true);define_v2_parameters(true);
m='bess_resource_standalone';load_system(fullfile(root,'models','resources',[m '.slx']));
b=[m '/BESS Resource'];ph=get_param(b,'PortHandles');
assert(isscalar(ph.Inport)&&isscalar(ph.Outport)&&isscalar([ph.LConn ph.RConn]), ...
    'BESS Resource must expose one CommandBus, one StatusBus and one PCC port.');

required={ ...
    [b '/01 BESS Source and DC Side'], ...
    [b '/02 PCS/01 GFM Strategy'], ...
    [b '/02 PCS/02 Virtual Impedance Policy'], ...
    [b '/02 PCS/03 Virtual Impedance Interface'], ...
    [b '/02 PCS/04 Common Protection and Limiter'], ...
    [b '/02 PCS/05 Average Voltage Converter'], ...
    [b '/03 AC Interface/Inverter-side R1 + L1'], ...
    [b '/03 AC Interface/Damped Shunt C'], ...
    [b '/03 AC Interface/Grid-side R2 + L2'], ...
    [b '/03 AC Interface/Step-up Transformer']};
for k=1:numel(required)
    assert(getSimulinkBlockHandle(required{k})>0,['Missing architecture block: ' required{k}]);
end

strategyOut=get_param([b '/02 PCS/01 GFM Strategy/GFMVoltageCommandBus'],'OutDataTypeStr');
viOut=get_param([b '/02 PCS/02 Virtual Impedance Policy/VirtualImpedanceCommandBus'],'OutDataTypeStr');
assert(strcmp(strategyOut,'Bus: GFMVoltageCommandBus'));
assert(strcmp(viOut,'Bus: VirtualImpedanceCommandBus'));
orderBlocks={'01 GFM Strategy','02 Virtual Impedance Policy', ...
    '03 Virtual Impedance Interface','04 Common Protection and Limiter', ...
    '05 Average Voltage Converter'};
x=zeros(1,numel(orderBlocks));
for k=1:numel(orderBlocks)
    p=get_param([b '/02 PCS/' orderBlocks{k}],'Position');x(k)=p(1);
end
assert(all(diff(x)>0),'GFM processing chain is not readable left-to-right.');
bad=find_system(b,'LookUnderMasks','all','Regexp','on', ...
    'Name','(?i)(PLL|PWM|Id ref|Iq ref)');
assert(isempty(bad),'BESS resource exposes or contains prohibited GFL/PWM command paths.');

mark_bus(m,[b '/02 PCS/06 Status Interface/GFM PCS Status'],'gfm_status');
mark_bus(m,[b '/01 BESS Source and DC Side/02 Limits and Availability/BESS DC Status'],'bess_dc_status');
set_param(m,'StopTime','0.8');o=sim(m);x=o.get('bess_v2_result');
g=read_bus(o.logsout.get('gfm_status').Values, ...
    {'frequency_Hz','Iactual_Arms','current_limit_factor','limit_active', ...
    'virtual_impedance_enabled','virtual_impedance_drop_V','control_mode','healthy'});
d=read_bus(o.logsout.get('bess_dc_status').Values, ...
    {'SOC_pu','Vdc_V','battery_current_A','battery_current_limit_factor', ...
    'charge_allowed','discharge_allowed'});

pre=x(:,1)>.20&x(:,1)<.28;post=x(:,1)>.68;
R=struct();R.pre=summarize(x,pre);R.post=summarize(x,post);
assert(all(isfinite(x),'all'),'Non-finite resource status.');
assert(abs(R.pre.P_W-4e6)<.12e6&&abs(R.post.P_W-5e6)<.20e6, ...
    'BESS active-power load following regression.');
assert(abs(R.pre.Q_var-1.2e6)<.12e6&&abs(R.post.Q_var-1.5e6)<.15e6, ...
    'BESS reactive-power delivery regression.');
assert(R.pre.Vpcc_V>9.0e3&&R.post.Vpcc_V>8.5e3&&R.post.Vpcc_V<10.5e3, ...
    'PCC voltage outside commissioning band.');
assert(abs(R.pre.frequency_Hz-50)<.03&&R.post.frequency_Hz>49.65&&R.post.frequency_Hz<49.90, ...
    'P-f droop response regression.');
assert(series(g.virtual_impedance_enabled(end,:))>.99, ...
    'Virtual impedance policy is not enabled.');
assert(mean(window(g.virtual_impedance_drop_V,.68,.80))>1, ...
    'Virtual impedance interface did not produce a physical voltage drop.');
assert(min(series(g.current_limit_factor))>.90, ...
    'Nominal load step unexpectedly drove the backup current limiter.');
assert(all(series(d.SOC_pu)>=.20&series(d.SOC_pu)<=.90),'SOC outside permitted range.');
assert(abs(series(d.Vdc_V(end,:))-1500)<1,'DC boundary voltage regression.');
assert(max(abs(series(d.battery_current_A)))<4500,'Battery current limit exceeded.');
assert(min(series(d.battery_current_limit_factor))>.90, ...
    'Nominal step drove the DC current limiter too deeply.');
assert(min(series(d.charge_allowed))>.5&&min(series(d.discharge_allowed))>.5, ...
    'Nominal SOC should retain bidirectional headroom.');
assert(series(g.healthy(end,:))>.5&&series(g.control_mode(end,:))==1);

fprintf(['BESS_RESOURCE_V2_ACCEPTANCE_PASS=1\n' ...
    'PRE  P=%.4fMW Q=%.4fMvar V=%.3fkV f=%.4fHz\n' ...
    'POST P=%.4fMW Q=%.4fMvar V=%.3fkV f=%.4fHz\n' ...
    'VI_DROP_POST=%.3fV SOC_END=%.6f\n'], ...
    R.pre.P_W/1e6,R.pre.Q_var/1e6,R.pre.Vpcc_V/1e3,R.pre.frequency_Hz, ...
    R.post.P_W/1e6,R.post.Q_var/1e6,R.post.Vpcc_V/1e3,R.post.frequency_Hz, ...
    mean(window(g.virtual_impedance_drop_V,.68,.80)),series(d.SOC_pu(end,:)));
close_system(m,0);
end

function mark_bus(m,p,name)
set_param(m,'SignalLogging','on','SignalLoggingName','logsout');ph=get_param(p,'PortHandles');
set_param(ph.Outport(1),'DataLogging','on','DataLoggingNameMode','Custom','DataLoggingName',name);
end

function b=read_bus(v,names)
b=struct();
for k=1:numel(names)
    ts=v.(names{k});b.(names{k})=[ts.Time(:) squeeze(ts.Data(:))];
end
end

function s=summarize(x,k)
s=struct('P_W',mean(x(k,2)),'Q_var',mean(x(k,3)), ...
    'Vpcc_V',mean(x(k,4)),'frequency_Hz',mean(x(k,5)), ...
    'limit_factor',mean(x(k,8)),'SOC_pu',mean(x(k,9)),'Vdc_V',mean(x(k,10)));
end
function y=series(x),y=x(:,2);end
function y=window(x,a,b),k=x(:,1)>=a&x(:,1)<=b;y=x(k,2);end
