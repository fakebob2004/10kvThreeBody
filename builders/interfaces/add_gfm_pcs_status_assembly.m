function path=add_gfm_pcs_status_assembly(parent,name,pos)
%ADD_GFM_PCS_STATUS_ASSEMBLY Adapt local GFM buses to the stable PCS status.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[0.92,0.92,0.92]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','strategy + VI + protection -> GFMPCSStatusBus');
types={'GFMVoltageCommandBus','GFMProtectionStatusBus', ...
    'VirtualImpedanceCommandBus','double','ResourceCommandBus'};
names={'Strategy','Protection','Virtual Impedance','VI Drop','Command'};
for k=1:5
    args={'Port',num2str(k),'Position',[20 45+65*(k-1) 50 59+65*(k-1)]};
    if ~strcmp(types{k},'double'),args=[args {'OutDataTypeStr',['Bus: ' types{k}]}];end %#ok<AGROW>
    add_block('simulink/Ports & Subsystems/In1',[path '/' names{k}],args{:});
end
add_block('simulink/Signal Routing/Bus Selector',[path '/Strategy Selector'], ...
    'Position',[90 25 95 125],'OutputSignals','theta_rad,omega_rad_s,Vll_ref_V');
add_block('simulink/Math Operations/Gain',[path '/omega to Hz'], ...
    'Position',[150 70 235 100],'Gain','1/(2*pi)');
add_block('simulink/Math Operations/Gain',[path '/Vll Command Pass'], ...
    'Position',[150 115 245 145],'Gain','1');
add_block('simulink/Signal Routing/Bus Selector',[path '/Protection Selector'], ...
    'Position',[90 145 95 245], ...
    'OutputSignals','Iactual_Arms,current_limit_factor,limit_active');
add_block('simulink/Signal Routing/Bus Selector',[path '/VI Selector'], ...
    'Position',[90 260 95 315],'OutputSignals','enable');
add_block('simulink/Math Operations/Gain',[path '/VI Enabled Pass'], ...
    'Position',[150 270 245 300],'Gain','1');
add_block('simulink/Signal Routing/Bus Selector',[path '/Mode Selector'], ...
    'Position',[90 365 95 420],'OutputSignals','mode');
add_block('simulink/Math Operations/Gain',[path '/Control Mode Pass'], ...
    'Position',[150 375 245 405],'Gain','1');
add_block('simulink/Sources/Constant',[path '/Healthy'], ...
    'Position',[150 430 245 460],'Value','1');
add_block('simulink/Signal Routing/Bus Creator',[path '/GFM PCS Status'], ...
    'Position',[350 25 355 470],'Inputs','10','OutDataTypeStr','Bus: GFMPCSStatusBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/GFMPCSStatusBus'], ...
    'Position',[430 235 460 249],'OutDataTypeStr','Bus: GFMPCSStatusBus');
add_line(path,'Strategy/1','Strategy Selector/1');
add_line(path,'Protection/1','Protection Selector/1');
add_line(path,'Virtual Impedance/1','VI Selector/1');
add_line(path,'Command/1','Mode Selector/1');
add_line(path,'Strategy Selector/2','omega to Hz/1');
add_line(path,'Strategy Selector/3','Vll Command Pass/1');
add_line(path,'VI Selector/1','VI Enabled Pass/1');
add_line(path,'Mode Selector/1','Control Mode Pass/1');
src={'Strategy Selector/1','omega to Hz/1','Vll Command Pass/1', ...
    'Protection Selector/1','Protection Selector/2','Protection Selector/3', ...
    'VI Enabled Pass/1','VI Drop/1','Control Mode Pass/1','Healthy/1'};
fields={'theta_rad','frequency_Hz','Vll_command_V','Iactual_Arms', ...
    'current_limit_factor','limit_active','virtual_impedance_enabled', ...
    'virtual_impedance_drop_V','control_mode','healthy'};
for k=1:10
    if any(k==[1 4 5 6])
        add_line(path,src{k},sprintf('GFM PCS Status/%d',k),'autorouting','on');
    else
        v2_named_line(path,src{k},sprintf('GFM PCS Status/%d',k),fields{k});
    end
end
add_line(path,'GFM PCS Status/1','GFMPCSStatusBus/1');v2_route_level(path);
end
