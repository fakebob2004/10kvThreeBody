function path=add_virtual_impedance_interface(parent,name,cfg,pos)
%ADD_VIRTUAL_IMPEDANCE_INTERFACE Layered local R+jX application.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[0.88,0.82,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','current conditioning -> R+jX drop -> compensated voltage command');
add_block('simulink/Ports & Subsystems/In1',[path '/GFMVoltageCommandBus'], ...
    'Position',[20 55 50 69],'OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/In1',[path '/iabc_converter_A'], ...
    'Position',[20 145 50 159],'Port','2');
add_block('simulink/Ports & Subsystems/In1',[path '/VirtualImpedanceCommandBus'], ...
    'Position',[20 235 50 249],'Port','3','OutDataTypeStr','Bus: VirtualImpedanceCommandBus');
add_current_conditioning(path,'01 Current Conditioning',cfg,[120 105 350 195]);
add_vi_drop(path,'02 R+jX Drop',[430 105 650 235]);
add_command_compensation(path,'03 Voltage Command Compensation',[740 45 1030 190]);
add_block('simulink/Ports & Subsystems/Out1',[path '/GFMVoltageCommandBus Out'], ...
    'Position',[1110 85 1140 99],'Port','1','OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/virtual_impedance_drop_V'], ...
    'Position',[1110 215 1140 229],'Port','2');
add_line(path,'iabc_converter_A/1','01 Current Conditioning/1');
add_line(path,'01 Current Conditioning/1','02 R+jX Drop/1');
add_line(path,'VirtualImpedanceCommandBus/1','02 R+jX Drop/2','autorouting','on');
add_line(path,'GFMVoltageCommandBus/1','03 Voltage Command Compensation/1','autorouting','on');
add_line(path,'02 R+jX Drop/1','03 Voltage Command Compensation/2');
add_line(path,'03 Voltage Command Compensation/1','GFMVoltageCommandBus Out/1');
add_line(path,'02 R+jX Drop/2','virtual_impedance_drop_V/1','autorouting','on');
v2_route_level(path);
end

function add_current_conditioning(parent,name,cfg,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[0.92,0.88,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','abc measurement filters + Clarke transform');
add_block('simulink/Ports & Subsystems/In1',[s '/iabc_A'], ...
    'Position',[20 105 50 119]);
add_block('simulink/Signal Routing/Demux',[s '/Split Current'], ...
    'Position',[90 55 95 190],'Outputs','3');
for k=1:3
    y=45+60*(k-1);
    add_block('simulink/Continuous/Transfer Fcn', ...
        [s sprintf('/Current Filter %c','A'+k-1)], ...
        'Position',[145 y 250 y+30],'Numerator','1', ...
        'Denominator',['[' cfg '.control.virtual_impedance_measurement_tau_s 1]']);
end
add_block('simulink/Signal Routing/Mux',[s '/Filtered Current abc'], ...
    'Position',[300 45 305 205],'Inputs','3');
add_block('simulink/Math Operations/Gain',[s '/Clarke Current'], ...
    'Position',[355 100 480 145], ...
    'Gain','sqrt(2/3)*[1 -0.5 -0.5;0 sqrt(3)/2 -sqrt(3)/2]', ...
    'Multiplication','Matrix(K*u)');
add_block('simulink/Ports & Subsystems/Out1',[s '/i_alpha_beta_A'], ...
    'Position',[535 115 565 129]);
add_line(s,'iabc_A/1','Split Current/1');
for k=1:3
    n=sprintf('Current Filter %c','A'+k-1);
    add_line(s,sprintf('Split Current/%d',k),[n '/1']);
    add_line(s,[n '/1'],sprintf('Filtered Current abc/%d',k));
end
add_line(s,'Filtered Current abc/1','Clarke Current/1');
add_line(s,'Clarke Current/1','i_alpha_beta_A/1');v2_route_level(s);
end

function add_vi_drop(parent,name,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[0.90,0.84,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','dV = enable*(R*i + X*J*i)');
add_block('simulink/Ports & Subsystems/In1',[s '/i_alpha_beta_A'], ...
    'Position',[20 75 50 89]);
add_block('simulink/Ports & Subsystems/In1',[s '/VirtualImpedanceCommandBus'], ...
    'Position',[20 185 50 199],'Port','2','OutDataTypeStr','Bus: VirtualImpedanceCommandBus');
add_block('simulink/Signal Routing/Bus Selector',[s '/VI Selector'], ...
    'Position',[85 150 90 245],'OutputSignals','enable,R_ohm,X_ohm');
add_block('simulink/Math Operations/Gain',[s '/Quadrature Current'], ...
    'Position',[130 95 250 135],'Gain','[0 -1;1 0]','Multiplication','Matrix(K*u)');
add_block('simulink/Math Operations/Product',[s '/R Drop'], ...
    'Position',[300 45 345 90]);
add_block('simulink/Math Operations/Product',[s '/X Drop'], ...
    'Position',[300 115 345 160]);
add_block('simulink/Math Operations/Sum',[s '/Drop alpha beta'], ...
    'Position',[395 65 430 140],'Inputs','++');
add_block('simulink/Math Operations/Product',[s '/Apply Enable'], ...
    'Position',[475 75 520 130]);
add_block('simulink/Math Operations/Gain',[s '/Inverse Clarke'], ...
    'Position',[570 80 700 125], ...
    'Gain','sqrt(2/3)*[1 0;-0.5 sqrt(3)/2;-0.5 -sqrt(3)/2]', ...
    'Multiplication','Matrix(K*u)');
add_block('simulink/User-Defined Functions/Fcn',[s '/Drop RMS'], ...
    'Position',[740 145 875 180],'Expr','sqrt((u(1)^2+u(2)^2+u(3)^2)/3)');
add_block('simulink/Ports & Subsystems/Out1',[s '/dVabc_V'], ...
    'Position',[925 90 955 104],'Port','1');
add_block('simulink/Ports & Subsystems/Out1',[s '/drop_rms_V'], ...
    'Position',[925 155 955 169],'Port','2');
add_line(s,'VirtualImpedanceCommandBus/1','VI Selector/1');
add_line(s,'i_alpha_beta_A/1','R Drop/1');
add_line(s,'i_alpha_beta_A/1','Quadrature Current/1');
add_line(s,'VI Selector/2','R Drop/2','autorouting','on');
add_line(s,'Quadrature Current/1','X Drop/1');
add_line(s,'VI Selector/3','X Drop/2','autorouting','on');
add_line(s,'R Drop/1','Drop alpha beta/1');add_line(s,'X Drop/1','Drop alpha beta/2');
add_line(s,'Drop alpha beta/1','Apply Enable/1');add_line(s,'VI Selector/1','Apply Enable/2','autorouting','on');
add_line(s,'Apply Enable/1','Inverse Clarke/1');
add_line(s,'Inverse Clarke/1','dVabc_V/1');add_line(s,'Inverse Clarke/1','Drop RMS/1');
add_line(s,'Drop RMS/1','drop_rms_V/1');v2_route_level(s);
end

function add_command_compensation(parent,name,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[0.92,0.88,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','raw voltage command - virtual drop');
add_block('simulink/Ports & Subsystems/In1',[s '/GFMVoltageCommandBus'], ...
    'Position',[20 65 50 79],'OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/In1',[s '/dVabc_V'], ...
    'Position',[20 190 50 204],'Port','2');
add_block('simulink/Signal Routing/Bus Selector',[s '/Command Selector'], ...
    'Position',[85 35 90 150], ...
    'OutputSignals','vabc_V,theta_rad,omega_rad_s,Vll_ref_V,enabled');
add_block('simulink/Math Operations/Sum',[s '/Compensated Voltage'], ...
    'Position',[180 55 215 115],'Inputs','+-');
add_block('simulink/Signal Routing/Bus Creator',[s '/Compensated Command'], ...
    'Position',[300 30 305 245],'Inputs','5','OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/Out1',[s '/GFMVoltageCommandBus Out'], ...
    'Position',[370 125 400 139],'OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_line(s,'GFMVoltageCommandBus/1','Command Selector/1');
add_line(s,'Command Selector/1','Compensated Voltage/1');
add_line(s,'dVabc_V/1','Compensated Voltage/2');
v2_named_line(s,'Compensated Voltage/1','Compensated Command/1','vabc_V');
for k=2:5
    add_line(s,sprintf('Command Selector/%d',k),sprintf('Compensated Command/%d',k),'autorouting','on');
end
add_line(s,'Compensated Command/1','GFMVoltageCommandBus Out/1');v2_route_level(s);
end
