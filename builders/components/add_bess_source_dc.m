function path=add_bess_source_dc(parent,name,cfg,pos)
%ADD_BESS_SOURCE_DC Two-stage replaceable BESS energy/DC boundary.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[1.00,0.95,0.72]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','5 MW / 10 MWh | replaceable energy model -> local limits/status');
add_block('simulink/Ports & Subsystems/In1',[path '/PCCMeasurementBus'], ...
    'Position',[20 115 50 129],'OutDataTypeStr','Bus: PCCMeasurementBus');
add_energy_state(path,'01 Energy and DC State',cfg,[120 55 410 200]);
add_availability(path,'02 Limits and Availability',cfg,[500 55 820 220]);
add_block('simulink/Ports & Subsystems/Out1',[path '/BESSStatusBus'], ...
    'Position',[900 90 930 104],'Port','1','OutDataTypeStr','Bus: BESSStatusBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/SourceStatusBus'], ...
    'Position',[900 175 930 189],'Port','2','OutDataTypeStr','Bus: SourceStatusBus');
add_line(path,'PCCMeasurementBus/1','01 Energy and DC State/1','autorouting','on');
add_line(path,'01 Energy and DC State/1','02 Limits and Availability/1','autorouting','on');
add_line(path,'02 Limits and Availability/1','BESSStatusBus/1','autorouting','on');
add_line(path,'02 Limits and Availability/2','SourceStatusBus/1','autorouting','on');
v2_route_level(path);
end

function add_energy_state(parent,name,cfg,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[1.00,0.91,0.62]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','PCC P -> DC buffer/loss -> SOC, Vdc, Ibat');
add_block('simulink/Ports & Subsystems/In1',[s '/PCCMeasurementBus'], ...
    'Position',[20 100 50 114],'OutDataTypeStr','Bus: PCCMeasurementBus');
add_block('simulink/Signal Routing/Bus Selector',[s '/PCC Power'], ...
    'Position',[80 75 85 135],'OutputSignals','P_W');
add_block('simulink/Continuous/Transfer Fcn',[s '/DC Power Buffer'], ...
    'Position',[125 85 245 120],'Numerator','1', ...
    'Denominator',['[' cfg '.control.P_measurement_tau_s 1]']);
add_block('simulink/Math Operations/Gain',[s '/Discharge Loss'], ...
    'Position',[285 35 395 65],'Gain',['1/' cfg '.source.discharge_efficiency']);
add_block('simulink/Math Operations/Gain',[s '/Charge Loss'], ...
    'Position',[285 145 395 175],'Gain',[cfg '.source.charge_efficiency']);
add_block('simulink/Signal Routing/Switch',[s '/Directional Loss'], ...
    'Position',[435 70 485 140],'Criteria','u2 >= Threshold','Threshold','0');
add_block('simulink/Math Operations/Gain',[s '/SOC Rate'], ...
    'Position',[530 50 635 85],'Gain',['-1/(' cfg '.source.E_Wh*3600)']);
add_block('simulink/Continuous/Integrator',[s '/SOC State'], ...
    'Position',[680 45 720 85],'InitialCondition',[cfg '.source.SOC_initial'], ...
    'LimitOutput','on','UpperSaturationLimit',[cfg '.source.SOC_max'], ...
    'LowerSaturationLimit',[cfg '.source.SOC_min']);
add_block('simulink/Math Operations/Gain',[s '/Battery Current'], ...
    'Position',[530 135 635 170],'Gain',['1/' cfg '.source.battery_nominal_V']);
add_block('simulink/Sources/Constant',[s '/DC-Link Voltage'], ...
    'Position',[675 125 790 155],'Value',[cfg '.source.dc_ref_V']);
add_block('simulink/Signal Routing/Bus Creator',[s '/BESS DC State'], ...
    'Position',[845 35 850 180],'Inputs','3','OutDataTypeStr','Bus: BESSDCStateBus');
add_block('simulink/Ports & Subsystems/Out1',[s '/BESSDCStateBus'], ...
    'Position',[910 95 940 109],'OutDataTypeStr','Bus: BESSDCStateBus');
add_line(s,'PCCMeasurementBus/1','PCC Power/1');
add_line(s,'PCC Power/1','DC Power Buffer/1');
add_line(s,'DC Power Buffer/1','Discharge Loss/1');
add_line(s,'DC Power Buffer/1','Directional Loss/2','autorouting','on');
add_line(s,'DC Power Buffer/1','Charge Loss/1');
add_line(s,'Discharge Loss/1','Directional Loss/1');
add_line(s,'Charge Loss/1','Directional Loss/3');
add_line(s,'Directional Loss/1','SOC Rate/1');
add_line(s,'Directional Loss/1','Battery Current/1');
add_line(s,'SOC Rate/1','SOC State/1');
sig={'SOC State/1','DC-Link Voltage/1','Battery Current/1'};
fields={'SOC_pu','Vdc_V','battery_current_A'};
for k=1:3,v2_named_line(s,sig{k},sprintf('BESS DC State/%d',k),fields{k});end
add_line(s,'BESS DC State/1','BESSDCStateBus/1');v2_route_level(s);
end

function add_availability(parent,name,cfg,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[1.00,0.86,0.58]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','SOC direction + Ibat limit -> common resource status');
add_block('simulink/Ports & Subsystems/In1',[s '/BESSDCStateBus'], ...
    'Position',[20 135 50 149],'OutDataTypeStr','Bus: BESSDCStateBus');
add_block('simulink/Signal Routing/Bus Selector',[s '/DC State Selector'], ...
    'Position',[85 70 90 215],'OutputSignals','SOC_pu,Vdc_V,battery_current_A');
add_block('simulink/Math Operations/Abs',[s '/Ibat Magnitude'], ...
    'Position',[150 185 200 220]);
add_block('simulink/User-Defined Functions/Fcn',[s '/Ibat Limit Factor'], ...
    'Position',[245 180 400 220], ...
    'Expr',[cfg '.source.Ibat_limit_A/(u+' cfg '.source.Ibat_limit_A*1e-6)']);
add_block('simulink/Discontinuities/Saturation',[s '/Limit Bounds'], ...
    'Position',[440 180 520 220],'LowerLimit','0','UpperLimit','1');
add_block('simulink/Logic and Bit Operations/Compare To Constant',[s '/Discharge Allowed'], ...
    'Position',[150 35 285 70],'relop','>','const',[cfg '.source.SOC_min']);
add_block('simulink/Logic and Bit Operations/Compare To Constant',[s '/Charge Allowed'], ...
    'Position',[150 95 285 130],'relop','<','const',[cfg '.source.SOC_max']);
add_block('simulink/Signal Attributes/Data Type Conversion',[s '/Discharge Allowed Double'], ...
    'Position',[325 35 365 70],'OutDataTypeStr','double');
add_block('simulink/Signal Attributes/Data Type Conversion',[s '/Charge Allowed Double'], ...
    'Position',[325 95 365 130],'OutDataTypeStr','double');
add_block('simulink/Math Operations/Gain',[s '/Discharge Headroom'], ...
    'Position',[405 35 515 70],'Gain',[cfg '.rating.P_W']);
add_block('simulink/Math Operations/Gain',[s '/Charge Headroom'], ...
    'Position',[405 95 515 130],'Gain',[cfg '.rating.P_W']);
add_block('simulink/Signal Routing/Bus Creator',[s '/BESS DC Status'], ...
    'Position',[610 25 615 275],'Inputs','8','OutDataTypeStr','Bus: BESSStatusBus');
add_block('simulink/Ports & Subsystems/Out1',[s '/BESSStatusBus'], ...
    'Position',[690 105 720 119],'Port','1','OutDataTypeStr','Bus: BESSStatusBus');
add_block('simulink/Math Operations/Gain',[s '/Available Power Pass'], ...
    'Position',[570 320 675 350],'Gain','1');
add_block('simulink/Sources/Constant',[s '/Dispatch Rating'], ...
    'Position',[570 365 675 395],'Value',[cfg '.rating.P_W']);
add_block('simulink/Math Operations/Gain',[s '/Energy State Pass'], ...
    'Position',[570 410 675 440],'Gain','1');
add_block('simulink/Sources/Constant',[s '/Not MPPT'], ...
    'Position',[570 500 675 530],'Value','1');
add_block('simulink/Signal Routing/Bus Creator',[s '/Source Status'], ...
    'Position',[735 315 740 545],'Inputs','5','OutDataTypeStr','Bus: SourceStatusBus');
add_block('simulink/Ports & Subsystems/Out1',[s '/SourceStatusBus'], ...
    'Position',[810 420 840 434],'Port','2','OutDataTypeStr','Bus: SourceStatusBus');
add_line(s,'BESSDCStateBus/1','DC State Selector/1');
add_line(s,'DC State Selector/1','Discharge Allowed/1');
add_line(s,'DC State Selector/1','Charge Allowed/1');
add_line(s,'DC State Selector/3','Ibat Magnitude/1');
add_line(s,'Ibat Magnitude/1','Ibat Limit Factor/1');
add_line(s,'Ibat Limit Factor/1','Limit Bounds/1');
add_line(s,'Discharge Allowed/1','Discharge Allowed Double/1');
add_line(s,'Charge Allowed/1','Charge Allowed Double/1');
add_line(s,'Discharge Allowed Double/1','Discharge Headroom/1');
add_line(s,'Charge Allowed Double/1','Charge Headroom/1');
add_line(s,'DC State Selector/1','BESS DC Status/1','autorouting','on');
add_line(s,'DC State Selector/2','BESS DC Status/2','autorouting','on');
add_line(s,'DC State Selector/3','BESS DC Status/3','autorouting','on');
sig={'Limit Bounds/1','Charge Headroom/1','Discharge Headroom/1', ...
    'Charge Allowed Double/1','Discharge Allowed Double/1'};
fields={'battery_current_limit_factor','charge_headroom_W','discharge_headroom_W', ...
    'charge_allowed','discharge_allowed'};
for k=1:5,v2_named_line(s,sig{k},sprintf('BESS DC Status/%d',k+3),fields{k});end
add_line(s,'BESS DC Status/1','BESSStatusBus/1');
add_line(s,'Discharge Headroom/1','Available Power Pass/1','autorouting','on');
add_line(s,'DC State Selector/1','Energy State Pass/1','autorouting','on');
ss={'Available Power Pass/1','Dispatch Rating/1','Energy State Pass/1', ...
    'DC State Selector/2','Not MPPT/1'};
sf={'available_power_W','dispatch_limit_W','energy_state_pu','Vdc_V','mppt_capture_pu'};
for k=1:5
    if k==4,add_line(s,ss{k},sprintf('Source Status/%d',k),'autorouting','on');
    else,v2_named_line(s,ss{k},sprintf('Source Status/%d',k),sf{k});end
end
add_line(s,'Source Status/1','SourceStatusBus/1');v2_route_level(s);
end
