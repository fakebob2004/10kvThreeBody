function path=add_gfm_common_protection(parent,name,cfg,pos)
%ADD_GFM_COMMON_PROTECTION Common voltage bounds, SOC interlock and backup foldback.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[1.00,0.82,0.72]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','strategy-independent voltage/SOC/current backup protection');
add_block('simulink/Ports & Subsystems/In1',[path '/GFMVoltageCommandBus'], ...
    'Position',[20 55 50 69],'OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/In1',[path '/iabc_converter_A'], ...
    'Position',[20 145 50 159],'Port','2');
add_block('simulink/Ports & Subsystems/In1',[path '/PCCMeasurementBus'], ...
    'Position',[20 220 50 234],'Port','3','OutDataTypeStr','Bus: PCCMeasurementBus');
add_block('simulink/Ports & Subsystems/In1',[path '/BESSStatusBus'], ...
    'Position',[20 300 50 314],'Port','4','OutDataTypeStr','Bus: BESSStatusBus');
add_block('simulink/Signal Routing/Bus Selector',[path '/Voltage Selector'], ...
    'Position',[85 30 90 105],'OutputSignals','vabc_V');
add_block('simulink/Signal Routing/Bus Selector',[path '/PCC Selector'], ...
    'Position',[85 205 90 260],'OutputSignals','P_W');
add_block('simulink/Signal Routing/Bus Selector',[path '/BESS Selector'], ...
    'Position',[85 280 90 375], ...
    'OutputSignals','charge_allowed,discharge_allowed,battery_current_limit_factor');
add_block('simulink/Signal Routing/Demux',[path '/Split Current'], ...
    'Position',[125 105 130 215],'Outputs','3');
for k=1:3
    y=105+50*(k-1);
    add_block('simulink/Continuous/Transfer Fcn', ...
        [path sprintf('/Current Filter %c','A'+k-1)], ...
        'Position',[165 y 265 y+30],'Numerator','1', ...
        'Denominator',['[' cfg '.control.current_limit_tau_s 1]']);
end
add_block('simulink/Signal Routing/Mux',[path '/Filtered Current abc'], ...
    'Position',[285 105 290 225],'Inputs','3');
add_block('simulink/User-Defined Functions/Fcn',[path '/Current RMS'], ...
    'Position',[300 130 435 170],'Expr','sqrt((u(1)^2+u(2)^2+u(3)^2)/3)');
add_block('simulink/User-Defined Functions/Fcn',[path '/Current Limit Factor'], ...
    'Position',[480 125 625 170], ...
    'Expr',[cfg '.control.Ilimit_rms_A/(u+' cfg '.control.Ilimit_rms_A*1e-6)']);
add_block('simulink/Discontinuities/Saturation',[path '/Factor Bounds'], ...
    'Position',[670 130 745 165],'LowerLimit','0','UpperLimit','1');
add_block('simulink/User-Defined Functions/Fcn',[path '/SOC Direction Factor'], ...
    'Position',[300 255 500 295], ...
    'Expr','(u(1)>=0)*u(3)+(u(1)<0)*u(2)');
add_block('simulink/Signal Routing/Mux',[path '/SOC Direction Inputs'], ...
    'Position',[240 225 245 330],'Inputs','3');
add_block('simulink/Continuous/Transfer Fcn',[path '/Power Direction Filter'], ...
    'Position',[125 220 220 250],'Numerator','1', ...
    'Denominator',['[' cfg '.control.P_measurement_tau_s 1]']);
add_block('simulink/Math Operations/MinMax',[path '/Combined Protection Factor'], ...
    'Position',[790 160 850 230],'Function','min','Inputs','3');
add_block('simulink/Math Operations/Product',[path '/Protected Voltage'], ...
    'Position',[905 55 950 110]);
phaseLimit=['sqrt(2/3)*' cfg '.control.Vmax_pu*' cfg '.rating.V_ac_low_V'];
add_block('simulink/Discontinuities/Saturation',[path '/Phase Voltage Bounds'], ...
    'Position',[990 60 1110 105],'LowerLimit',['-' phaseLimit], ...
    'UpperLimit',phaseLimit);
add_block('simulink/Logic and Bit Operations/Compare To Constant',[path '/Limit Active'], ...
    'Position',[905 160 1015 195],'relop','<','const','0.999999');
add_block('simulink/Signal Attributes/Data Type Conversion',[path '/Limit Active Double'], ...
    'Position',[1035 160 1080 195],'OutDataTypeStr','double');
add_block('simulink/Ports & Subsystems/Out1',[path '/vabc_command_V'], ...
    'Position',[1160 70 1190 84],'Port','1');
add_block('simulink/Signal Routing/Bus Creator',[path '/Protection Status'], ...
    'Position',[1115 135 1120 285],'Inputs','3', ...
    'OutDataTypeStr','Bus: GFMProtectionStatusBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/GFMProtectionStatusBus'], ...
    'Position',[1180 200 1210 214],'Port','2', ...
    'OutDataTypeStr','Bus: GFMProtectionStatusBus');

add_line(path,'GFMVoltageCommandBus/1','Voltage Selector/1');
add_line(path,'PCCMeasurementBus/1','PCC Selector/1');
add_line(path,'BESSStatusBus/1','BESS Selector/1');
add_line(path,'iabc_converter_A/1','Split Current/1');
for k=1:3
    n=sprintf('Current Filter %c','A'+k-1);
    add_line(path,sprintf('Split Current/%d',k),[n '/1']);
    add_line(path,[n '/1'],sprintf('Filtered Current abc/%d',k));
end
add_line(path,'Filtered Current abc/1','Current RMS/1');
add_line(path,'Current RMS/1','Current Limit Factor/1');
add_line(path,'Current Limit Factor/1','Factor Bounds/1');
add_line(path,'PCC Selector/1','Power Direction Filter/1');
add_line(path,'Power Direction Filter/1','SOC Direction Inputs/1');
add_line(path,'BESS Selector/1','SOC Direction Inputs/2');
add_line(path,'BESS Selector/2','SOC Direction Inputs/3');
add_line(path,'SOC Direction Inputs/1','SOC Direction Factor/1');
add_line(path,'Factor Bounds/1','Combined Protection Factor/1');
add_line(path,'SOC Direction Factor/1','Combined Protection Factor/2');
add_line(path,'BESS Selector/3','Combined Protection Factor/3','autorouting','on');
add_line(path,'Voltage Selector/1','Protected Voltage/1');
add_line(path,'Combined Protection Factor/1','Protected Voltage/2');
add_line(path,'Protected Voltage/1','Phase Voltage Bounds/1');
add_line(path,'Combined Protection Factor/1','Limit Active/1');
add_line(path,'Limit Active/1','Limit Active Double/1');
add_line(path,'Phase Voltage Bounds/1','vabc_command_V/1');
v2_named_line(path,'Current RMS/1','Protection Status/1','Iactual_Arms');
v2_named_line(path,'Combined Protection Factor/1','Protection Status/2','current_limit_factor');
v2_named_line(path,'Limit Active Double/1','Protection Status/3','limit_active');
add_line(path,'Protection Status/1','GFMProtectionStatusBus/1');v2_route_level(path);
end
