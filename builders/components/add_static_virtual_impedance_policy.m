function path=add_static_virtual_impedance_policy(parent,name,cfg,pos)
%ADD_STATIC_VIRTUAL_IMPEDANCE_POLICY Stable policy boundary for future dynamic VI.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[0.88,0.82,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','replaceable static/dynamic VI policy -> enable, R, X');
add_block('simulink/Ports & Subsystems/In1',[path '/PCCMeasurementBus'], ...
    'Position',[20 55 50 69],'OutDataTypeStr','Bus: PCCMeasurementBus');
add_block('simulink/Ports & Subsystems/In1',[path '/iabc_converter_A'], ...
    'Position',[20 115 50 129],'Port','2');
add_block('simulink/Sinks/Terminator',[path '/Reserved PCC Input'], ...
    'Position',[170 50 190 70]);
add_block('simulink/Sinks/Terminator',[path '/Reserved Current Input'], ...
    'Position',[170 110 190 130]);
add_block('simulink/Sources/Constant',[path '/VI Enable'], ...
    'Position',[300 25 440 60],'Value',[cfg '.control.virtual_impedance_enabled']);
add_block('simulink/Sources/Constant',[path '/R virtual'], ...
    'Position',[300 85 440 120], ...
    'Value',[cfg '.control.Rvirt_pu*(' cfg '.rating.V_ac_low_V^2/' cfg '.rating.S_VA)']);
add_block('simulink/Sources/Constant',[path '/X virtual'], ...
    'Position',[300 145 440 180], ...
    'Value',[cfg '.control.Xvirt_pu*(' cfg '.rating.V_ac_low_V^2/' cfg '.rating.S_VA)']);
add_block('simulink/Signal Routing/Bus Creator',[path '/VI Command'], ...
    'Position',[520 25 525 190],'Inputs','3','OutDataTypeStr','Bus: VirtualImpedanceCommandBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/VirtualImpedanceCommandBus'], ...
    'Position',[610 100 640 114],'OutDataTypeStr','Bus: VirtualImpedanceCommandBus');
add_line(path,'PCCMeasurementBus/1','Reserved PCC Input/1');
add_line(path,'iabc_converter_A/1','Reserved Current Input/1');
signals={'VI Enable/1','R virtual/1','X virtual/1'};fields={'enable','R_ohm','X_ohm'};
for k=1:3,v2_named_line(path,signals{k},sprintf('VI Command/%d',k),fields{k});end
add_line(path,'VI Command/1','VirtualImpedanceCommandBus/1');v2_route_level(path);
end
