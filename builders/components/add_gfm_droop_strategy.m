end

function add_voltage_synthesis(parent,name,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[0.88,0.95,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','theta + Vll + enable -> vabc');
ports={'theta_rad','Vll_ref_V','enable'};
for k=1:3
    add_block('simulink/Ports & Subsystems/In1',[s '/' ports{k}], ...
        'Position',[20 45+65*(k-1) 50 59+65*(k-1)],'Port',num2str(k));
end
add_block('simulink/Math Operations/Gain',[s '/Phase Peak'], ...
    'Position',[90 105 185 140],'Gain','sqrt(2/3)');
phase={'A','B','C'};bias={'0','-2*pi/3','2*pi/3'};
for k=1:3
    y=25+70*(k-1);
    add_block('simulink/Math Operations/Bias',[s '/' phase{k} ' Phase'], ...
        'Position',[225 y 295 y+30],'Bias',bias{k});
    add_block('simulink/Math Operations/Trigonometric Function',[s '/' phase{k} ' Sine'], ...
        'Position',[335 y 400 y+30],'Operator','sin');
    add_block('simulink/Math Operations/Product',[s '/' phase{k} ' Voltage'], ...
        'Position',[445 y 490 y+35]);
    add_line(s,'theta_rad/1',[phase{k} ' Phase/1'],'autorouting','on');
    add_line(s,[phase{k} ' Phase/1'],[phase{k} ' Sine/1']);
    add_line(s,[phase{k} ' Sine/1'],[phase{k} ' Voltage/1']);
    add_line(s,'Phase Peak/1',[phase{k} ' Voltage/2'],'autorouting','on');
end
add_block('simulink/Signal Routing/Mux',[s '/Three-Phase Voltage'], ...
    'Position',[535 25 540 225],'Inputs','3');
for k=1:3,add_line(s,[phase{k} ' Voltage/1'],sprintf('Three-Phase Voltage/%d',k));end
add_block('simulink/Discontinuities/Saturation',[s '/Enable Bounds'], ...
    'Position',[225 250 315 285],'LowerLimit','0','UpperLimit','1');
add_block('simulink/Math Operations/Product',[s '/Apply Enable'], ...
    'Position',[585 90 630 145]);
add_line(s,'Vll_ref_V/1','Phase Peak/1');add_line(s,'enable/1','Enable Bounds/1');
add_line(s,'Three-Phase Voltage/1','Apply Enable/1');add_line(s,'Enable Bounds/1','Apply Enable/2','autorouting','on');
add_block('simulink/Ports & Subsystems/Out1',[s '/vabc_V'], ...
    'Position',[680 95 710 109],'Port','1');
add_block('simulink/Ports & Subsystems/Out1',[s '/enabled'], ...
    'Position',[680 260 710 274],'Port','2');
add_line(s,'Apply Enable/1','vabc_V/1');add_line(s,'Enable Bounds/1','enabled/1','autorouting','on');
v2_route_level(s);
end
