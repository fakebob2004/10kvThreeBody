function path=add_gfm_droop_strategy(parent,name,cfg,pos)
%ADD_GFM_DROOP_STRATEGY Layered P-f/Q-V strategy implementation.
path=[parent '/' name];add_block('built-in/Subsystem',path,'Position',pos, ...
    'BackgroundColor','[0.78,0.90,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','replaceable P-f/Q-V strategy -> typed voltage command');
add_block('simulink/Ports & Subsystems/In1',[path '/CommandBus'], ...
    'Position',[20 90 50 104],'OutDataTypeStr','Bus: ResourceCommandBus');
add_block('simulink/Ports & Subsystems/In1',[path '/PCCMeasurementBus'], ...
    'Position',[20 210 50 224],'Port','2','OutDataTypeStr','Bus: PCCMeasurementBus');
add_block('simulink/Signal Routing/Bus Selector',[path '/Command Selector'], ...
    'Position',[85 40 90 185],'OutputSignals','P_ref_W,Q_ref_var,V_ref_V,f_ref_Hz,enable');
add_block('simulink/Signal Routing/Bus Selector',[path '/PCC Selector'], ...
    'Position',[85 210 90 300],'OutputSignals','P_W,Q_var');
add_pf_law(path,'01 P-f Droop Law',cfg,[170 30 410 120]);
add_block('simulink/Continuous/Integrator',[path '/02 Angle Generator'], ...
    'Position',[475 55 535 95],'InitialCondition',[cfg '.control.theta0_rad']);
add_qv_law(path,'03 Q-V Droop Law',cfg,[170 190 410 280]);
add_voltage_synthesis(path,'04 Three-Phase Voltage Synthesis',[610 55 910 260]);
add_block('simulink/Signal Routing/Bus Creator',[path '/Voltage Command Bus'], ...
    'Position',[985 35 990 280],'Inputs','5','OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_block('simulink/Ports & Subsystems/Out1',[path '/GFMVoltageCommandBus'], ...
    'Position',[1060 145 1090 159],'OutDataTypeStr','Bus: GFMVoltageCommandBus');
add_line(path,'CommandBus/1','Command Selector/1');
add_line(path,'PCCMeasurementBus/1','PCC Selector/1');
add_line(path,'Command Selector/1','01 P-f Droop Law/1','autorouting','on');
add_line(path,'PCC Selector/1','01 P-f Droop Law/2','autorouting','on');
add_line(path,'Command Selector/4','01 P-f Droop Law/3','autorouting','on');
add_line(path,'01 P-f Droop Law/1','02 Angle Generator/1');
add_line(path,'Command Selector/2','03 Q-V Droop Law/1','autorouting','on');
add_line(path,'PCC Selector/2','03 Q-V Droop Law/2','autorouting','on');
add_line(path,'Command Selector/3','03 Q-V Droop Law/3','autorouting','on');
add_line(path,'02 Angle Generator/1','04 Three-Phase Voltage Synthesis/1');
add_line(path,'03 Q-V Droop Law/1','04 Three-Phase Voltage Synthesis/2');
add_line(path,'Command Selector/5','04 Three-Phase Voltage Synthesis/3','autorouting','on');
sig={'04 Three-Phase Voltage Synthesis/1','02 Angle Generator/1', ...
    '01 P-f Droop Law/1','03 Q-V Droop Law/1','04 Three-Phase Voltage Synthesis/2'};
fields={'vabc_V','theta_rad','omega_rad_s','Vll_ref_V','enabled'};
for k=1:5,v2_named_line(path,sig{k},sprintf('Voltage Command Bus/%d',k),fields{k});end
add_line(path,'Voltage Command Bus/1','GFMVoltageCommandBus/1');v2_route_level(path);
end

function add_pf_law(parent,name,cfg,pos)
s=[parent '/' name];add_block('built-in/Subsystem',s,'Position',pos, ...
    'BackgroundColor','[0.84,0.93,1.00]','ContentPreviewEnabled','off', ...
    'AttributesFormatString','omega = 2*pi*fref + mp*(Pref-P)');
ports={'P_ref_W','P_meas_W','f_ref_Hz'};
for k=1:3
    add_block('simulink/Ports & Subsystems/In1',[s '/' ports{k}], ...
        'Position',[20 35+55*(k-1) 50 49+55*(k-1)],'Port',num2str(k));
end
add_block('simulink/Continuous/Transfer Fcn',[s '/P Measurement Filter'], ...
    'Position',[90 85 200 120],'Numerator','1', ...
    'Denominator',['[' cfg '.control.P_measurement_tau_s 1]']);
add_block('simulink/Math Operations/Sum',[s '/P Error'], ...
    'Position',[245 35 280 90],'Inputs','+-');
add_block('simulink/Math Operations/Gain',[s '/P-f Droop'], ...
    'Position',[325 45 445 80], ...
    'Gain',['2*pi*' cfg '.control.P_f_Hz_per_MW/1e6']);
add_block('simulink/Math Operations/Gain',[s '/Frequency Reference'], ...
    'Position',[325 120 445 155],'Gain','2*pi');
add_block('simulink/Math Operations/Sum',[s '/Omega Command'], ...
    'Position',[495 65 530 135],'Inputs','++');
add_block('simulink/Ports & Subsystems/Out1',[s '/omega_rad_s'], ...
    'Position',[585 95 615 109]);
add_line(s,'P_ref_W/1','P Error/1');add_line(s,'P_meas_W/1','P Measurement Filter/1');
add_line(s,'P Measurement Filter/1','P Error/2');add_line(s,'P Error/1','P-f Droop/1');
add_line(s,'P-f Droop/1','Omega Command/1');add_line(s,'f_ref_Hz/1','Frequency Reference/1');
add_line(s,'Frequency Reference/1','Omega Command/2');add_line(s,'Omega Command/1','omega_rad_s/1');
v2_route_level(s);
end

